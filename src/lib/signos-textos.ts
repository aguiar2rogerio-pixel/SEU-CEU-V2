// 🔧 FUNÇÕES DE AJUDA
// ------------------------------
function normalizarSigno(signo: string): string {
  return signo
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

export function getTextoSol(signo: string | null | undefined) {
  if (!signo) return null;
  const chave = normalizarSigno(signo) as keyof typeof SOL;
  return SOL[chave] || null;
}

export function getTextoLua(signo: string | null | undefined) {
  if (!signo) return null;
  const chave = normalizarSigno(signo) as keyof typeof LUA;
  return LUA[chave] || null;
}

export function getTextoAscendente(signo: string | null | undefined) {
  if (!signo) return null;
  const chave = normalizarSigno(signo) as keyof typeof ASCENDENTE;
  return ASCENDENTE[chave] || null;
}
